/**
 * 田字平铺：把一张 w×h 的图**原样铺成 2×2**，得到一张 2w×2h 的位图。
 * 返回四份的落点（左上、右上、左下、右下）。
 *
 * 为什么是「铺四份」而不是「切成四块再拼回」：切成四块再按原位拼回，得到的就是原图本身 ——
 * 屏上什么变化都没有，也就无从看接缝（第一版就错在这儿）。要检验的是这张图能不能像壁纸
 * 那样和自己接上：每一格的右边紧挨着另一格的左边、下边紧挨着上边，十字处那两条接缝才是对象。
 *
 * 四份必须画进**同一张 canvas**：非整数倍缩放下浏览器会在独立元素之间画亚像素亮缝
 * （README 第 29 条），那条缝是渲染凭空造的，而这里要判的恰恰是有没有缝。
 * 落点都是整像素（0 与 w、0 与 h），同一张位图里相邻两次绘制之间不会留下半像素透明缝。
 *
 * @param {number} w 原图像素宽
 * @param {number} h 原图像素高
 * @returns {Array<{dx:number, dy:number}>} 四份的左上角落点；尺寸不足 1 像素时返回空数组，
 *   让调用方拒绝（`drawImage` 的源宽高传 0 是浏览器差异区：有的当空操作、有的抛错）
 */
export function tilePlacements(w, h) {
  // `!(w >= 1)` 同时挡掉 undefined / NaN / 0 / 负数
  if (!(w >= 1) || !(h >= 1)) return [];
  return [
    { dx: 0, dy: 0 },
    { dx: w, dy: 0 },
    { dx: 0, dy: h },
    { dx: w, dy: h },
  ];
}
